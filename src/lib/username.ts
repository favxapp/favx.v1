const RESERVED_SET: ReadonlySet<string> = new Set(RESERVED_SLUGS);

export type UsernameProblem = 'format' | 'reserved';

/** NFKC + trim + minúsculas (A-03: normalização consistente). */
export function normalizeUsername(input: string): string {
  return input.normalize('NFKC').trim().toLowerCase();
}

export function usernameProblem(input: string): UsernameProblem | null {
  const n = normalizeUsername(input);
  if (!USERNAME_REGEX.test(n)) return 'format';
  if (RESERVED_SET.has(n)) return 'reserved';
  return null;
}
